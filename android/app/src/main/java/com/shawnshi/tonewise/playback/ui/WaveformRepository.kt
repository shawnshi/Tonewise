package com.shawnshi.tonewise.playback.ui

import android.content.Context
import android.net.Uri
import android.os.Environment
import android.provider.DocumentsContract
import android.util.LruCache
import dagger.hilt.android.qualifiers.ApplicationContext
import java.io.File
import javax.inject.Inject
import javax.inject.Singleton
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import com.shawnshi.tonewise.music.MusicSettings
import org.oxycblt.musikr.Music
import org.oxycblt.musikr.Song
import org.oxycblt.musikr.core.TonewiseCore
import timber.log.Timber as L

/**
 * Resolves precomputed 150-point RMS waveform envelopes from `/Music/.tonewise/waveforms.bin`
 * generated by `tonewise-cli`.
 */
@Singleton
class WaveformRepository
@Inject
constructor(
    @ApplicationContext private val context: Context,
    private val musicSettings: MusicSettings,
) {
    private val envelopeCache = LruCache<Music.UID, FloatArray>(128)
    private val fingerprintCache = LruCache<Music.UID, String>(256)

    @Volatile private var cachedArchiveUri: Uri? = null

    suspend fun getEnvelope(song: Song): FloatArray? {
        envelopeCache.get(song.uid)?.let { return it }

        return withContext(Dispatchers.IO) {
            try {
                val blake3Hex = getOrComputeBlake3(song) ?: return@withContext null
                val envelope =
                    lookupFromSyncedCache(blake3Hex)
                        ?: lookupFromSafArchive(blake3Hex)
                        ?: lookupFromExternalMusicFile(blake3Hex)
                if (envelope != null && envelope.size == 150) {
                    envelopeCache.put(song.uid, envelope)
                    envelope
                } else {
                    null
                }
            } catch (e: Throwable) {
                L.d("Waveform lookup unavailable for ${song.path}: ${e.message}")
                null
            }
        }
    }

    fun invalidateArchiveCache() {
        cachedArchiveUri = null
        envelopeCache.evictAll()
    }

    private fun lookupFromSyncedCache(blake3Hex: String): FloatArray? {
        val synced = File(context.filesDir, ".tonewise/waveforms.bin")
        if (!synced.isFile) return null
        return TonewiseCore.lookupWaveformPath(synced.absolutePath, blake3Hex)
    }

    private fun getOrComputeBlake3(song: Song): String? {
        fingerprintCache.get(song.uid)?.let { return it }
        return context.contentResolver.openFileDescriptor(song.uri, "r")?.use { pfd ->
            val fp = TonewiseCore.audioFingerprint(pfd)
            fingerprintCache.put(song.uid, fp.audioFrameBlake3Hex)
            fp.audioFrameBlake3Hex
        }
    }

    private fun lookupFromSafArchive(blake3Hex: String): FloatArray? {
        val uri = cachedArchiveUri ?: findSafWaveformsUri()?.also { cachedArchiveUri = it } ?: return null
        return try {
            context.contentResolver.openFileDescriptor(uri, "r")?.use { pfd ->
                TonewiseCore.lookupWaveform(pfd, blake3Hex)
            }
        } catch (e: Exception) {
            cachedArchiveUri = null
            null
        }
    }

    private fun lookupFromExternalMusicFile(blake3Hex: String): FloatArray? {
        @Suppress("DEPRECATION")
        val musicDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_MUSIC)
        val binFile = File(musicDir, ".tonewise/waveforms.bin")
        if (!binFile.isFile) return null
        return TonewiseCore.lookupWaveformPath(binFile.absolutePath, blake3Hex)
    }

    private fun findSafWaveformsUri(): Uri? {
        for (location in musicSettings.safQuery.source) {
            val rootDocId = DocumentsContract.getTreeDocumentId(location.uri)
            val tonewiseId = findChildDocumentId(location.uri, rootDocId, ".tonewise") ?: continue
            val binId = findChildDocumentId(location.uri, tonewiseId, "waveforms.bin") ?: continue
            return DocumentsContract.buildDocumentUriUsingTree(location.uri, binId)
        }
        return null
    }

    private fun findChildDocumentId(treeUri: Uri, parentDocId: String, targetName: String): String? {
        val childrenUri = DocumentsContract.buildChildDocumentsUriUsingTree(treeUri, parentDocId)
        val projection =
            arrayOf(
                DocumentsContract.Document.COLUMN_DOCUMENT_ID,
                DocumentsContract.Document.COLUMN_DISPLAY_NAME,
            )
        return try {
            context.contentResolver.query(childrenUri, projection, null, null, null)?.use { cursor ->
                val idIdx = cursor.getColumnIndexOrThrow(DocumentsContract.Document.COLUMN_DOCUMENT_ID)
                val nameIdx =
                    cursor.getColumnIndexOrThrow(DocumentsContract.Document.COLUMN_DISPLAY_NAME)
                while (cursor.moveToNext()) {
                    if (cursor.getString(nameIdx).equals(targetName, ignoreCase = true)) {
                        return@use cursor.getString(idIdx)
                    }
                }
                null
            }
        } catch (_: Exception) {
            null
        }
    }
}
