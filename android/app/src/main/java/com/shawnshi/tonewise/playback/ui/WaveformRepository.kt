package com.shawnshi.tonewise.playback.ui

import android.content.Context
import android.net.Uri
import android.os.Environment
import android.provider.DocumentsContract
import android.util.LruCache
import dagger.hilt.android.qualifiers.ApplicationContext
import java.io.File
import javax.inject.Inject
import javax.inject.Singleton
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import com.shawnshi.tonewise.music.MusicSettings
import com.shawnshi.tonewise.sync.AudioFingerprintCacheEntity
import com.shawnshi.tonewise.sync.TonewiseSyncDatabase
import org.oxycblt.musikr.Music
import org.oxycblt.musikr.Song
import org.oxycblt.musikr.core.TonewiseCore
import timber.log.Timber as L

/**
 * Resolves precomputed 150-point RMS waveform envelopes from `/Music/.tonewise/waveforms.bin`
 * generated by `tonewise-cli`.
 */
@Singleton
class WaveformRepository
@Inject
constructor(
    @ApplicationContext private val context: Context,
    private val musicSettings: MusicSettings,
) {
    private val syncDb: TonewiseSyncDatabase by lazy { TonewiseSyncDatabase.getInstance(context) }
    private val envelopeCache = LruCache<Music.UID, FloatArray>(128)
    private val fingerprintCache = LruCache<Music.UID, String>(256)
    private val persistentFpCache = LruCache<String, AudioFingerprintCacheEntity>(2048)
    private val fpInitLock = Any()
    @Volatile private var dbMigrated = false

    @Volatile private var cachedArchiveUri: Uri? = null
    @Volatile private var archiveMissingCheckedAtMs = 0L

    fun getCachedEnvelope(uid: Music.UID): FloatArray? = envelopeCache.get(uid)

    suspend fun getEnvelope(song: Song): FloatArray? {
        envelopeCache.get(song.uid)?.let { return it }

        val archiveOrDisk =
            withContext(Dispatchers.IO) {
                try {
                    if (hasAnyWaveformArchive()) {
                        val blake3Hex = getOrComputeBlake3(song)
                        if (blake3Hex != null) {
                            val fromArchive =
                                lookupFromSyncedCache(blake3Hex)
                                    ?: lookupFromSafArchive(blake3Hex)
                                    ?: lookupFromExternalMusicFile(blake3Hex)
                            if (fromArchive != null && fromArchive.size == LocalWaveformExtractor.ENVELOPE_POINTS) {
                                envelopeCache.put(song.uid, fromArchive)
                                return@withContext fromArchive
                            }
                        }
                    }

                    val fromDisk = readLocalDiskCache(song)
                    if (fromDisk != null && fromDisk.size == LocalWaveformExtractor.ENVELOPE_POINTS) {
                        envelopeCache.put(song.uid, fromDisk)
                        return@withContext fromDisk
                    }
                    null
                } catch (e: Throwable) {
                    L.d("Waveform archive/disk lookup failed for ${song.path}: ${e.message}")
                    null
                }
            }
        if (archiveOrDisk != null) {
            return archiveOrDisk
        }

        val extracted =
            withContext(Dispatchers.Default) {
                LocalWaveformExtractor.extract(context, song.uri, song.durationMs)
            } ?: return null

        if (extracted.size == LocalWaveformExtractor.ENVELOPE_POINTS) {
            envelopeCache.put(song.uid, extracted)
            withContext(Dispatchers.IO) {
                writeLocalDiskCache(song, extracted)
            }
            return extracted
        }
        return null
    }

    private fun localCacheFileFor(song: Song): File {
        val cacheDir = File(context.cacheDir, LOCAL_WAVEFORM_CACHE_DIR)
        val safeUid = song.uid.toString().replace(Regex("[^a-zA-Z0-9._-]"), "_")
        return File(cacheDir, "${safeUid}_${song.size}_${song.modifiedMs}.wf150")
    }

    internal fun readLocalDiskCache(song: Song): FloatArray? {
        val file = localCacheFileFor(song)
        if (!file.isFile || file.length() != LocalWaveformExtractor.ENVELOPE_POINTS.toLong()) {
            return null
        }
        return runCatching {
                LocalWaveformExtractor.dequantizeFromBytes(file.readBytes())
            }
            .getOrNull()
    }

    internal fun writeLocalDiskCache(song: Song, envelope: FloatArray) {
        if (envelope.size != LocalWaveformExtractor.ENVELOPE_POINTS) return
        runCatching {
            val dir = File(context.cacheDir, LOCAL_WAVEFORM_CACHE_DIR)
            if (!dir.exists()) dir.mkdirs()
            val target = localCacheFileFor(song)
            val tmp = File(dir, "${target.name}.tmp")
            tmp.writeBytes(LocalWaveformExtractor.quantizeToBytes(envelope))
            if (!tmp.renameTo(target)) {
                tmp.copyTo(target, overwrite = true)
                tmp.delete()
            }
            pruneLocalDiskCacheIfNeeded(dir)
        }
    }

    private fun pruneLocalDiskCacheIfNeeded(dir: File) {
        val files = dir.listFiles { f -> f.isFile && f.name.endsWith(".wf150") } ?: return
        if (files.size <= MAX_LOCAL_CACHE_FILES) return
        files.sortBy { it.lastModified() }
        val toRemove = files.size - MAX_LOCAL_CACHE_FILES
        for (i in 0 until toRemove) {
            files[i].delete()
        }
    }

    fun invalidateArchiveCache() {
        cachedArchiveUri = null
        archiveMissingCheckedAtMs = 0L
        envelopeCache.evictAll()
    }

    private fun ensureDbReady() {
        if (dbMigrated) return
        synchronized(fpInitLock) {
            if (dbMigrated) return
            syncDb.ensureLegacyMigrated(context)
            dbMigrated = true
        }
    }

    private fun hasAnyWaveformArchive(): Boolean {
        val checkedAt = archiveMissingCheckedAtMs
        if (checkedAt > 0L && (System.currentTimeMillis() - checkedAt) < ARCHIVE_NEGATIVE_CACHE_MS) {
            return false
        }
        if (File(context.filesDir, ".tonewise/waveforms.bin").isFile) {
            archiveMissingCheckedAtMs = 0L
            return true
        }
        @Suppress("DEPRECATION")
        val musicDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_MUSIC)
        if (File(musicDir, ".tonewise/waveforms.bin").isFile) {
            archiveMissingCheckedAtMs = 0L
            return true
        }
        val foundSaf =
            runCatching { (cachedArchiveUri ?: findSafWaveformsUri()?.also { cachedArchiveUri = it }) != null }
                .getOrDefault(false)
        if (foundSaf) {
            archiveMissingCheckedAtMs = 0L
            return true
        }
        archiveMissingCheckedAtMs = System.currentTimeMillis()
        return false
    }

    private fun lookupFromSyncedCache(blake3Hex: String): FloatArray? {
        val synced = File(context.filesDir, ".tonewise/waveforms.bin")
        if (!synced.isFile) return null
        return TonewiseCore.lookupWaveformPath(synced.absolutePath, blake3Hex)
    }

    fun getOrComputeAudioFrameBlake3(song: Song): String? =
        runCatching { getOrComputeBlake3(song) }.getOrNull()

    private fun getOrComputeBlake3(song: Song): String? {
        fingerprintCache.get(song.uid)?.let { return it }
        ensureDbReady()
        val uidStr = song.uid.toString()
        val cachedEntity =
            synchronized(fpInitLock) { persistentFpCache.get(uidStr) }
                ?: syncDb.audioFingerprintDao().getByUid(uidStr)?.also { loaded ->
                    synchronized(fpInitLock) { persistentFpCache.put(uidStr, loaded) }
                }
        cachedEntity
            ?.takeIf { cached ->
                cached.fileSize == song.size &&
                    (cached.mtimeMs == 0L ||
                        song.modifiedMs <= 0L ||
                        kotlin.math.abs(cached.mtimeMs - song.modifiedMs) <= 2_000L)
            }
            ?.audioFrameBlake3Hex
            ?.let { cachedHex ->
                fingerprintCache.put(song.uid, cachedHex)
                return cachedHex
            }
        return context.contentResolver.openFileDescriptor(song.uri, "r")?.use { pfd ->
            val fp = TonewiseCore.audioFingerprint(pfd)
            fingerprintCache.put(song.uid, fp.audioFrameBlake3Hex)
            val entity =
                AudioFingerprintCacheEntity(
                    trackUid = uidStr,
                    fileSize = song.size,
                    audioFrameBlake3Hex = fp.audioFrameBlake3Hex,
                    headerBlake3Hex = fp.headerBlake3Hex,
                    headerSize = fp.headerSize,
                    updatedAtMs = System.currentTimeMillis(),
                    mtimeMs = song.modifiedMs,
                )
            synchronized(fpInitLock) { persistentFpCache.put(uidStr, entity) }
            syncDb.audioFingerprintDao().upsert(entity)
            fp.audioFrameBlake3Hex
        }
    }

    private fun lookupFromSafArchive(blake3Hex: String): FloatArray? {
        val uri = cachedArchiveUri ?: findSafWaveformsUri()?.also { cachedArchiveUri = it } ?: return null
        return try {
            context.contentResolver.openFileDescriptor(uri, "r")?.use { pfd ->
                TonewiseCore.lookupWaveform(pfd, blake3Hex)
            }
        } catch (e: Exception) {
            cachedArchiveUri = null
            null
        }
    }

    private fun lookupFromExternalMusicFile(blake3Hex: String): FloatArray? {
        @Suppress("DEPRECATION")
        val musicDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_MUSIC)
        val binFile = File(musicDir, ".tonewise/waveforms.bin")
        if (!binFile.isFile) return null
        return TonewiseCore.lookupWaveformPath(binFile.absolutePath, blake3Hex)
    }

    private fun findSafWaveformsUri(): Uri? {
        for (location in musicSettings.safQuery.source) {
            val rootDocId = DocumentsContract.getTreeDocumentId(location.uri)
            val tonewiseId = findChildDocumentId(location.uri, rootDocId, ".tonewise") ?: continue
            val binId = findChildDocumentId(location.uri, tonewiseId, "waveforms.bin") ?: continue
            return DocumentsContract.buildDocumentUriUsingTree(location.uri, binId)
        }
        return null
    }

    private fun findChildDocumentId(treeUri: Uri, parentDocId: String, targetName: String): String? {
        val childrenUri = DocumentsContract.buildChildDocumentsUriUsingTree(treeUri, parentDocId)
        val projection =
            arrayOf(
                DocumentsContract.Document.COLUMN_DOCUMENT_ID,
                DocumentsContract.Document.COLUMN_DISPLAY_NAME,
            )
        return try {
            context.contentResolver.query(childrenUri, projection, null, null, null)?.use { cursor ->
                val idIdx = cursor.getColumnIndexOrThrow(DocumentsContract.Document.COLUMN_DOCUMENT_ID)
                val nameIdx =
                    cursor.getColumnIndexOrThrow(DocumentsContract.Document.COLUMN_DISPLAY_NAME)
                while (cursor.moveToNext()) {
                    if (cursor.getString(nameIdx).equals(targetName, ignoreCase = true)) {
                        return@use cursor.getString(idIdx)
                    }
                }
                null
            }
        } catch (_: Exception) {
            null
        }
    }

    private companion object {
        const val ARCHIVE_NEGATIVE_CACHE_MS = 60_000L
        const val LOCAL_WAVEFORM_CACHE_DIR = "waveforms_v1"
        const val MAX_LOCAL_CACHE_FILES = 2000
    }
}
